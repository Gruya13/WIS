#!/usr/bin/env python3
"""
Build-HwTest.py
===============
Kompilacija WIS.HwTest.exe pomoću Mono Roslyn csc.exe i .NET Framework 4.8 referenci.
"""

import sys
import shutil
import hashlib
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
HWTEST_DIR = ROOT / "UI" / "HwTest"
REF_DIR = pathlib.Path.home() / ".local/share/wis-tools/net48/build/.NETFramework/v4.8"
CSC_EXE = pathlib.Path("/usr/lib/mono/4.5/csc.exe")

def main():
    if not CSC_EXE.exists():
        print(f"[-] Greška: Roslyn kompajler nije pronađen na {CSC_EXE}", file=sys.stderr)
        return 1

    if not REF_DIR.exists():
        print(f"[-] Greška: .NET Framework 4.8 reference nisu pronađene na {REF_DIR}", file=sys.stderr)
        return 1

    tmp = pathlib.Path("/tmp/wis-hwtest-build")
    tmp.mkdir(parents=True, exist_ok=True)

    attr_cs = tmp / ".NETFramework,Version=v4.8.AssemblyAttributes.cs"
    attr_cs.write_text(
        "// <autogenerated />\n"
        "using System;\n"
        "using System.Reflection;\n"
        "[assembly: global::System.Runtime.Versioning.TargetFrameworkAttribute(\".NETFramework,Version=v4.8\", FrameworkDisplayName = \".NET Framework 4.8\")]\n"
        "[assembly: AssemblyTitle(\"WIS.HwTest\")]\n"
        "[assembly: AssemblyProduct(\"WIS Hardware Test Suite\")]\n"
        "[assembly: AssemblyVersion(\"3.0.0.0\")]\n"
        "[assembly: AssemblyFileVersion(\"3.0.0.0\")]\n",
        encoding="utf-8"
    )

    out_exe = HWTEST_DIR / "WIS.HwTest.exe"
    if out_exe.exists():
        out_exe.unlink()

    zxing_dll = HWTEST_DIR / "zxing.dll"
    if not zxing_dll.exists():
        print(f"[-] Greška: zxing.dll nije pronađen u {zxing_dll}", file=sys.stderr)
        return 1

    sources = [
        str(HWTEST_DIR / "Program.cs"),
        str(HWTEST_DIR / "HwTestShell.cs"),
        str(HWTEST_DIR / "Interop" / "NativeMethods.cs"),
        str(ROOT / "UI" / "ThermalSensorEngine.cs"),
        str(HWTEST_DIR / "Core" / "ResultModel.cs"),
        str(HWTEST_DIR / "Core" / "HwTestLogger.cs"),
        str(HWTEST_DIR / "Core" / "ModelProfileClient.cs"),
        str(HWTEST_DIR / "Core" / "HardwareProbe.cs"),
        str(HWTEST_DIR / "Core" / "FactorySpecProbe.cs"),
        str(HWTEST_DIR / "Core" / "MazeGenerator.cs"),
        str(HWTEST_DIR / "Core" / "AutoHardwareDiagnostics.cs"),
        str(HWTEST_DIR / "Tests" / "DisplayTestWindow.cs"),
        str(HWTEST_DIR / "Tests" / "KeyboardTestWindow.cs"),
        str(HWTEST_DIR / "Tests" / "TouchpadTestWindow.cs"),
        str(HWTEST_DIR / "Tests" / "TouchscreenMazeWindow.cs"),
        str(HWTEST_DIR / "Tests" / "AudioTestWindow.cs"),
        str(HWTEST_DIR / "Tests" / "MicTestWindow.cs"),
        str(HWTEST_DIR / "Tests" / "CameraTestWindow.cs"),
        str(HWTEST_DIR / "Tests" / "FingerprintTestWindow.cs"),
        str(HWTEST_DIR / "Tests" / "UsbPortTestWindow.cs"),
        str(HWTEST_DIR / "Tests" / "GpuStressWindow.cs"),
        str(HWTEST_DIR / "Tests" / "AutoTestDetailsWindow.cs"),
        str(attr_cs),
    ]

    cmd = [
        "mono", str(CSC_EXE),
        "/noconfig", "/nowarn:1701,1702", "/nostdlib+",
        "/platform:anycpu", "/errorreport:prompt", "/warn:4",
        "/define:TRACE", "/highentropyva+", "/langversion:5",
        f"/reference:{REF_DIR}/mscorlib.dll",
        f"/reference:{REF_DIR}/System.dll",
        f"/reference:{REF_DIR}/System.Core.dll",
        f"/reference:{REF_DIR}/System.Data.dll",
        f"/reference:{REF_DIR}/System.Drawing.dll",
        f"/reference:{REF_DIR}/System.Management.dll",
        f"/reference:{REF_DIR}/System.Speech.dll",
        f"/reference:{REF_DIR}/System.Web.Extensions.dll",
        f"/reference:{REF_DIR}/System.Xaml.dll",
        f"/reference:{REF_DIR}/System.Xml.dll",
        f"/reference:{REF_DIR}/System.Xml.Linq.dll",
        f"/reference:{REF_DIR}/WindowsBase.dll",
        f"/reference:{REF_DIR}/PresentationCore.dll",
        f"/reference:{REF_DIR}/PresentationFramework.dll",
        f"/reference:{zxing_dll}",
        "/debug:pdbonly", "/filealign:512", "/optimize+",
        f"/out:{out_exe}",
        "/target:winexe",
    ]

    app_manifest = ROOT / "UI" / "app.manifest"
    if app_manifest.exists():
        cmd.append(f"/win32manifest:{app_manifest}")

    # Ugradi zxing.dll kao resurs (bez LibreHardwareMonitorLib/WinRing0 drajvera da Defender ne bi brisao .exe)
    cmd.append(f"/resource:{zxing_dll},Assets.zxing.dll")

    # Ugradi keyboard_layouts.json kao resurs
    layouts_json = HWTEST_DIR / "Assets" / "keyboard_layouts.json"
    if layouts_json.exists():
        cmd.append(f"/resource:{layouts_json},Assets.keyboard_layouts.json")

    # Ugradi cifre 0-9 kao resurse
    for d in range(10):
        wav = HWTEST_DIR / "Assets" / "digits_en" / f"{d}.wav"
        if wav.exists():
            cmd.append(f"/resource:{wav},Assets.digits_en.{d}.wav")

    cmd.extend(sources)

    print("[*] Kompajliram WIS.HwTest.exe preko Mono Roslyn csc.exe...")
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        print("[-] Kompilacija NIJE uspela! Exit code:", res.returncode, file=sys.stderr)
        if res.stdout:
            print("STDOUT:\n", res.stdout, file=sys.stderr)
        if res.stderr:
            print("STDERR:\n", res.stderr, file=sys.stderr)
        return res.returncode

    if not out_exe.exists():
        print("[-] Greška: Izlazni fajl nije pronađen!", file=sys.stderr)
        return 1

    size = out_exe.stat().st_size
    sha256 = hashlib.sha256(out_exe.read_bytes()).hexdigest()
    print(f"[+] USPEH! Generisan {out_exe.name}")
    print(f"    Veličina: {size:,} bajtova ({size / 1024:.1f} KB)")
    print(f"    SHA-256 : {sha256}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
